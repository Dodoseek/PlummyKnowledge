"""File storage port (ARCHITECTURE.md §8.5, SECURITY_MODEL.md §9).

- Keys are generated by the server: 32 random hex characters. A user's file name is never part of a key or a
  path, so a malicious name cannot leave the storage root (§12).
- Two areas: ``quarantine`` for files that have not passed validation yet (restricted, cleaned up by TTL)
  and ``documents`` for accepted originals and derived artefacts.
- ``put`` streams the data, enforces a size limit while reading and returns the size and SHA-256, so the
  caller never has to buffer a whole file.
"""

from __future__ import annotations

import re
import secrets
from collections.abc import AsyncIterable, AsyncIterator
from contextlib import AbstractAsyncContextManager
from dataclasses import dataclass
from datetime import datetime
from enum import StrEnum
from pathlib import Path
from typing import Final, Protocol

_KEY_PATTERN: Final = re.compile(r"^[0-9a-f]{32}$")


class StorageArea(StrEnum):
    QUARANTINE = "quarantine"
    DOCUMENTS = "documents"


@dataclass(frozen=True, slots=True)
class StorageKey:
    """Opaque object key: from ``StorageKey.new()`` or read back from the database, never from a client."""

    value: str

    def __post_init__(self) -> None:
        if not _KEY_PATTERN.fullmatch(self.value):
            raise ValueError("invalid storage key")

    @classmethod
    def new(cls) -> StorageKey:
        return cls(secrets.token_hex(16))

    def __str__(self) -> str:
        return self.value


@dataclass(frozen=True, slots=True)
class StoredObject:
    area: StorageArea
    key: StorageKey
    size_bytes: int
    sha256: bytes


class StorageError(Exception):
    """Base class for storage failures. Messages never contain file names or paths."""


class StorageObjectNotFoundError(StorageError):
    def __init__(self) -> None:
        super().__init__("storage object not found")


class StorageObjectExistsError(StorageError):
    def __init__(self) -> None:
        super().__init__("storage object already exists")


class StorageLimitExceededError(StorageError):
    """The stream was longer than ``max_bytes``; nothing was stored."""

    def __init__(self, limit: int) -> None:
        super().__init__(f"object exceeds {limit} bytes")
        self.limit = limit


class StorageProvider(Protocol):
    async def put(
        self,
        area: StorageArea,
        key: StorageKey,
        data: AsyncIterable[bytes],
        *,
        max_bytes: int | None = None,
    ) -> StoredObject:
        """Store a new object. Never overwrites: an existing key raises ``StorageObjectExistsError``."""
        ...

    def open(self, area: StorageArea, key: StorageKey) -> AsyncIterator[bytes]:
        """Stream the object's content."""
        ...

    def local_path(self, area: StorageArea, key: StorageKey) -> AbstractAsyncContextManager[Path]:
        """A read-only local file with the object's content for tools that need a path (the parser)."""
        ...

    async def move(self, key: StorageKey, source: StorageArea, target: StorageArea) -> None:
        """Move an object between areas (quarantine → documents) without overwriting the target."""
        ...

    async def delete(self, area: StorageArea, key: StorageKey) -> None:
        """Remove the object; a missing object is not an error (deletion jobs are retried)."""
        ...

    async def exists(self, area: StorageArea, key: StorageKey) -> bool: ...

    async def purge_expired(self, area: StorageArea, older_than: datetime) -> int:
        """Remove objects last modified before ``older_than``; returns how many were removed."""
        ...
